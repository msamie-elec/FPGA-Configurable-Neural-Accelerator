"""Host benchmark tests: deterministic vectors, percentiles, data integrity.

The mocked board validates benchmark plumbing. Real timing and FPGA results
can only be generated by the CLI with a connected physical device.
"""
import pathlib
import sys
import unittest
sys.path.insert(0,str(pathlib.Path(__file__).resolve().parents[1]/"host"))

from benchmark_npu import MODELS, benchmark_one, generate_inputs, percentile
from reference_scalable import infer


class FakeBoard:
    def __init__(self, corrupt=False):
        self.corrupt=corrupt
        self.config=None
    def load_demo_model(self, inputs, widths):
        self.config=(inputs,widths)
    def infer(self, sample):
        class Response:
            pass
        assert self.config is not None
        scores,winner=infer(sample,self.config[1])
        result=Response()
        result.scores=tuple(scores+[0]*(8-len(scores)))
        result.class_index=winner if not self.corrupt else (winner+1)%self.config[1][-1]
        return result


class BenchmarkTests(unittest.TestCase):
    def test_corner_and_random_vectors(self):
        self.assertEqual(generate_inputs(8,3,9)[1],[127]*8)
        self.assertEqual(generate_inputs(8,3,9)[2],[-128]*8)
        self.assertEqual(generate_inputs(8,10,9),generate_inputs(8,10,9))
        self.assertNotEqual(generate_inputs(8,10,9),generate_inputs(8,10,10))
    def test_percentiles(self):
        self.assertEqual(percentile([1,2,3,4,5],95),4.8)
        self.assertIsNone(percentile([],50))
    def test_three_networks(self):
        for name in MODELS:
            result,rows=benchmark_one(FakeBoard(),name,12,2,42)
            self.assertEqual(result["mismatches"],0)
            self.assertEqual(result["passes"],12)
            self.assertEqual(len(rows),12)
            self.assertIsNone(result["fpga_compute_latency_cycles"])
    def test_mismatch_is_not_suppressed(self):
        result,_=benchmark_one(FakeBoard(corrupt=True),"small",6,0,42)
        self.assertEqual(result["mismatches"],6)


if __name__=="__main__":
    unittest.main()
